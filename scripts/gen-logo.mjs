// Writes the DeepGit mark: a Git graph that reads as a tree (docs/design/ITERATION-3.md, section 13).
// The trunk is one lane with two commits. The crown is a binary tree of commits, and each level
// doubles the nodes, so the foliage gets denser away from the trunk.
//
// Run from anywhere: node scripts/gen-logo.mjs
// Writes src-tauri/icons/logo.svg (large, 6 levels), src-tauri/icons/logo-small.svg (small, 4 levels)
// and public/favicon.svg (small). PNG and ICO files are rendered from these SVGs separately.

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const REPO_ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");

const TILE = "#191A1C";
const ACCENT = "#4A86FF";
// Quarters of the crown, left to right, for levels 3 and deeper: lane 5, lane 1, lane 2, lane 7.
const QUARTER_COLOURS = ["#22D8EE", "#2FE08A", "#FFB52E", "#FF8A33"];
// Level 2: left node is lane 1, right node is lane 2.
const LEVEL_2_COLOURS = ["#2FE08A", "#FFB52E"];
const ROOT_Y = 880;
const ROOT_X = 512;

/** Parameters per variant. Radii and widths are indexed as the spec lists them (see the comments). */
export const VARIANTS = {
  large: {
    levels: 6,
    fork: [512, 610],
    radii: [150, 250, 322, 378, 424], // levels 2..L
    edgeWidths: [80, 56, 38, 26, 18, 12], // levels 1..L
    nodeRadii: [64, 64, 44, 32, 24, 18, 13], // levels 0..L
    span: 96, // leaf angles from -span to +span, in degrees
  },
  small: {
    levels: 4,
    fork: [512, 640],
    radii: [180, 300, 390], // levels 2..L
    edgeWidths: [96, 72, 56, 44], // levels 1..L
    nodeRadii: [92, 92, 66, 54, 46], // levels 0..L
    span: 80,
  },
};

const fmt = (v) => String(Math.round(v * 10) / 10);

function colourOf(k, i) {
  if (k <= 1) return ACCENT;
  if (k === 2) return LEVEL_2_COLOURS[i];
  return QUARTER_COLOURS[Math.floor((i * 4) / 2 ** (k - 1))];
}

/** Lays out one variant. Returns the edges (drawn first) and the nodes (drawn on top) in draw order. */
export function layout(name) {
  const v = VARIANTS[name];
  if (!v) throw new Error(`Unknown variant: ${name}`);
  const leafCount = 2 ** (v.levels - 1);
  const leafAngle = (j) => -v.span + (j * 2 * v.span) / (leafCount - 1);
  const [cx, cy] = v.fork;

  // Node records keyed by "k:i". Levels 0 and 1 are the root and the fork.
  const at = new Map();
  at.set("0:0", { k: 0, i: 0, x: ROOT_X, y: ROOT_Y, r: v.nodeRadii[0], fill: ACCENT });
  at.set("1:0", { k: 1, i: 0, x: cx, y: cy, r: v.nodeRadii[1], fill: ACCENT });
  for (let k = 2; k <= v.levels; k++) {
    const count = 2 ** (k - 1);
    const leavesBelow = leafCount / count;
    for (let i = 0; i < count; i++) {
      // The node's angle is the mean of the leaf angles below it.
      let sum = 0;
      for (let j = i * leavesBelow; j < (i + 1) * leavesBelow; j++) sum += leafAngle(j);
      const a = ((sum / leavesBelow) * Math.PI) / 180;
      const r = v.radii[k - 2];
      at.set(`${k}:${i}`, {
        k,
        i,
        x: cx + r * Math.sin(a),
        y: cy - r * Math.cos(a),
        r: v.nodeRadii[k],
        fill: colourOf(k, i),
      });
    }
  }

  const edges = [
    { d: `M${ROOT_X} ${ROOT_Y} V${fmt(cy)}`, w: v.edgeWidths[0], colour: ACCENT },
  ];
  for (let k = 2; k <= v.levels; k++) {
    for (let i = 0; i < 2 ** (k - 1); i++) {
      const Q = at.get(`${k}:${i}`);
      const P = at.get(`${k - 1}:${Math.floor(i / 2)}`);
      const d = Math.hypot(Q.x - P.x, Q.y - P.y);
      // Directions from the crown centre. The fork has no direction of its own, so it points up.
      const unit = (N) => {
        const dx = N.x - cx;
        const dy = N.y - cy;
        const len = Math.hypot(dx, dy);
        return len === 0 ? [0, -1] : [dx / len, dy / len];
      };
      const [pux, puy] = unit(P);
      const [qux, quy] = unit(Q);
      const c1 = [P.x + pux * 0.5 * d, P.y + puy * 0.5 * d];
      const c2 = [Q.x - qux * 0.4 * d, Q.y - quy * 0.4 * d];
      edges.push({
        d: `M${fmt(P.x)} ${fmt(P.y)} C${fmt(c1[0])} ${fmt(c1[1])} ${fmt(c2[0])} ${fmt(c2[1])} ${fmt(Q.x)} ${fmt(Q.y)}`,
        w: v.edgeWidths[k - 1],
        colour: Q.fill,
      });
    }
  }

  const nodes = [...at.values()]
    .sort((a, b) => a.k - b.k || a.i - b.i)
    .map((n) => ({ ...n, x: fmt(n.x), y: fmt(n.y), outline: Math.max(5, Math.round(0.3 * n.r)) }));
  return { edges, nodes };
}

/** SVG text for one variant. Edges come first, then nodes, so the node outlines cut the edges. */
export function svgOf(name) {
  const { edges, nodes } = layout(name);
  return [
    '<svg xmlns="http://www.w3.org/2000/svg" width="1024" height="1024" viewBox="0 0 1024 1024">',
    "  <!-- Generated by scripts/gen-logo.mjs (docs/design/ITERATION-3.md, section 13). Do not edit by hand. -->",
    `  <rect x="0" y="0" width="1024" height="1024" rx="224" ry="224" fill="${TILE}"/>`,
    '  <g fill="none" stroke-linecap="round">',
    ...edges.map((e) => `    <path d="${e.d}" stroke="${e.colour}" stroke-width="${e.w}"/>`),
    "  </g>",
    "  <!-- commit nodes: outlined in the tile colour so the lanes stay separate -->",
    `  <g stroke="${TILE}">`,
    ...nodes.map((n) => `    <circle cx="${n.x}" cy="${n.y}" r="${n.r}" fill="${n.fill}" stroke-width="${n.outline}"/>`),
    "  </g>",
    "</svg>",
    "",
  ].join("\n");
}

const TARGETS = [
  { file: "src-tauri/icons/logo.svg", variant: "large" },
  { file: "src-tauri/icons/logo-small.svg", variant: "small" },
  { file: "public/favicon.svg", variant: "small" },
];

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  for (const { file, variant } of TARGETS) {
    writeFileSync(join(REPO_ROOT, file), svgOf(variant));
    console.log(`wrote ${file} (${variant})`);
  }
}
